export function getProviderDataFlows(providerCode: string): ProviderDataFlow[] {
  return PROVIDER_DATA_FLOWS[providerCode.toLowerCase()] ?? [];
}

export function findDataFlowById(
  providers: { code: string; dataFlows: ProviderDataFlow[] }[],
  dataFlowId: string
): ProviderDataFlow | undefined {
  for (const p of providers) {
    const found = p.dataFlows.find((f) => f.id === dataFlowId);
    if (found) return found;
  }
  return undefined;
}
