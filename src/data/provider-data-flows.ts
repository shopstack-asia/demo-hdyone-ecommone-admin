type FlowInput = Omit<ProviderDataFlow, "id"> & { id?: string };

function flow(providerCode: string, f: FlowInput): ProviderDataFlow {
  return { ...f, id: f.id ?? `${providerCode}-${f.code.toLowerCase().replace(/_/g, "-")}` };
}

